-- Operação (Limpeza Industrial): agenda IGUAL à planilha "Ordens de Serviço - Limpeza
-- Industrial 2026.xlsx" (aba "Plano de Limpeza 2026"), que já traz uma OS aberta no SIGMA
-- pra CADA ocorrência (ex.: L-OP-1S TRIPPERS 05/10 = OS 046318, 12/10 = 046319...).
-- Pedido do usuário: "tem que ser igual a planilha".
--
-- 1. Nova tabela manutencao_os_previstas (plano, data, nº OS): a programação usa o número
--    da OS DA SEMANA na hora de programar, em vez de digitar toda semana.
-- 2. Planos L-OP-* da Operação: agenda_rigida (sem antecipação pelo alinhamento por
--    equipamento, sem corte por limite da equipe, sem folga de cobertura) + periodicidade
--    da sigla do nome + data_inicial = 1ª data da planilha. Com isso cada semana mostra
--    exatamente as OS da planilha — antes a S41 tinha 11 sugestões da Operação (mensais
--    do dia 15 puxados pelo alinhamento) em vez das 6 da planilha.
--
-- 15 tarefas, 344 OS (jan–dez/2026). Testes de disponibilidade (P-OP) ficam
-- como estão (migration 059). Nome casado sem acento/maiúscula, só planos ativos do Apoio.
-- Gerado a partir da planilha (script em scratchpad, não versionado).

-- 0) Conferência antes: cada tarefa da planilha deve casar com exatamente 1 plano ativo.
WITH tarefas(nome) AS (VALUES
  ('L-OP-1M PÁTIO DE CARVÃO'),
  ('L-OP-1M STACKER 01'),
  ('L-OP-1M STACKER 02'),
  ('L-OP-1M TCLD'),
  ('L-OP-1M TRIPPERS'),
  ('L-OP-1S PÁTIO DE CARVÃO'),
  ('L-OP-1S STACKER 01'),
  ('L-OP-1S STACKER 02'),
  ('L-OP-1S TRIPPERS'),
  ('L-OP-2M PÁTIO DE CARVÃO'),
  ('L-OP-2M STACKER 01'),
  ('L-OP-2M STACKER 02'),
  ('L-OP-2M TCLD'),
  ('L-OP-2S TCLD'),
  ('L-OP-2S TRIPPERS')
)
SELECT t.nome AS tarefa_planilha, count(p.id) AS planos_casados, string_agg(p.codigo, ', ') AS codigos
  FROM tarefas t
  LEFT JOIN manutencao_planos p ON p.area = 'APOIO' AND p.ativo AND upper(translate(regexp_replace(trim(p.nome), '[[:space:]]+', ' ', 'g'), 'ÁÀÃÂÉÊÍÓÔÕÚÇáàãâéêíóôõúç', 'AAAAEEIOOOUCaaaaeeiooouc')) = upper(translate(regexp_replace(trim(t.nome), '[[:space:]]+', ' ', 'g'), 'ÁÀÃÂÉÊÍÓÔÕÚÇáàãâéêíóôõúç', 'AAAAEEIOOOUCaaaaeeiooouc'))
 GROUP BY t.nome ORDER BY t.nome;

