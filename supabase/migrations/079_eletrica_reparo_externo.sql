-- Solicitação nova nasce aberta e sem dados de controle (quem abre não pula etapa).
CREATE OR REPLACE FUNCTION public.portal_validar_reparo() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF auth.role() = 'service_role' OR public.portal_role() = 'Admin' THEN RETURN NEW; END IF;
  IF TG_OP = 'INSERT' AND (NEW.status <> 'aberto' OR NEW.fornecedor IS NOT NULL OR NEW.valor_orcamento IS NOT NULL
      OR NEW.nf_remessa IS NOT NULL OR NEW.previsao_retorno IS NOT NULL OR NEW.teams_enviado_em IS NOT NULL) THEN
    RAISE EXCEPTION 'Solicitação nova deve estar aberta, sem dados de controle.' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS portal_validar_reparo ON public.eletrica_reparos;
CREATE TRIGGER portal_validar_reparo BEFORE INSERT ON public.eletrica_reparos
FOR EACH ROW EXECUTE FUNCTION public.portal_validar_reparo();

-- Histórico: uma linha na abertura e a cada troca de status (ou nova observação).
CREATE OR REPLACE FUNCTION public.portal_historico_reparo() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.status IS NOT DISTINCT FROM OLD.status
     AND NEW.status_observacao IS NOT DISTINCT FROM OLD.status_observacao THEN
    RETURN NEW;
  END IF;
  INSERT INTO public.eletrica_reparos_historico (reparo_id, status, observacao, usuario_id, usuario_nome)
  VALUES (
    NEW.id, NEW.status,
    CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE NEW.status_observacao END,
    auth.uid(),
    CASE WHEN TG_OP = 'INSERT' THEN NEW.solicitante_nome
         ELSE coalesce(NEW.status_atualizado_por, (SELECT name FROM public.profiles WHERE id = auth.uid())) END
  );
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS portal_historico_reparo ON public.eletrica_reparos;
CREATE TRIGGER portal_historico_reparo AFTER INSERT OR UPDATE ON public.eletrica_reparos
FOR EACH ROW EXECUTE FUNCTION public.portal_historico_reparo();

