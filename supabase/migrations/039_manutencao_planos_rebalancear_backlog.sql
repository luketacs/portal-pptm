-- A migration 038 reprogramou todo o backlog (planos ativos sem nenhum ciclo ainda) pra
-- uma única data (2026-09-21, primeira semana aberta) — mas como "próxima execução" sem
-- ciclo é a própria data_inicial, e a sugestão só casa na janela exata da semana
-- selecionada (ver preventivaVencendo em src/utils/manutencao-preventivas.ts), isso
-- empilhou os 748 planos inteiros na semana 39 e deixou toda semana seguinte vazia.
--
-- Redistribui esse mesmo backlog ao longo de várias semanas, com três regras combinadas
-- com o usuário, aplicadas nesta ordem de prioridade:
--
--   1. Planos do mesmo local/equipamento (campo `equipamento`, ex. "PRÉDIO 25 -
--      COORDENAÇÃO E ENGENHARIA PPTM", onde vários TAG/KKS distintos dividem a mesma
--      sala) têm que sair todos NA MESMA SEMANA — não faz sentido mandar o técnico na
--      mesma sala em semanas diferentes pra tarefas diferentes. O agrupamento é tratado
--      como unidade atômica: ou o grupo inteiro cabe na semana, ou ele inteiro vai pra
--      próxima.
--
--   2. Alguns desses grupos JÁ têm parte de seus planos com ordem real programada (ciclo
--      com ordem_id vinculado) — hoje, todos na semana 38 (2026-09-14), da leva de
--      programação recente. O restante do grupo (ainda no backlog) é puxado pra essa
--      MESMA semana real, em vez de entrar no rebalanceamento geral — senão a mesma sala
--      acabaria com uma tarefa na semana 38 (já programada de verdade) e outra na semana
--      que o algoritmo calculasse (ex. 39+), exatamente o que não pode acontecer.
--
--   3. Nenhuma semana pode ter mais de 8 preventivas "grandes" (periodicidade semestral+:
--      6, 12, 13, 24 meses) por área — perder o prazo de uma anual não é visível de novo
--      por meses (tolerância de atraso é ~1/3 do período), então não pode virar backlog
--      invisível. O resto da vaga da semana (até completar 25 no total — mesmo lote já
--      usado no painel de sugestões, LOTE_PREVENTIVAS_POR_SEMANA_NOVO em
--      manutencao-programacao.component.ts) é preenchido com as "pequenas" (< 6 meses).
--      Essa regra só se aplica aos grupos SEM semana real já fixada (regra 2) — esses
--      são posicionados semana a semana, cada grupo inteiro (regra 1) entrando na semana
--      corrente só se ainda couber nos dois limites (8 grandes / 25 total); senão, abre
--      a próxima semana.
--
