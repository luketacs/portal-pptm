-- Migration: 080_eletrica_ensaios_motores
-- Menu Elétrica — Ensaios de Motores. Substitui a planilha "ENSAIO DE MOTORES - MT" que a
-- Elétrica preenchia por motor: cadastro do motor (dados de placa) uma vez só e, a cada
-- ensaio, as leituras do megôhmetro. O portal avalia pela IEEE 43-2013 (resistência de
-- isolamento corrigida a 40 °C + índice de polarização) e mostra a tendência por TAG.
--
-- eletrica_equipamentos: um registro por TAG. tipo hoje só 'motor' — transformador e outros
--   entram em migration própria (com as colunas de placa que precisarem).
-- eletrica_ensaios: um registro por ensaio, numerado EN-001 (mesmo esquema do RE-001, 079).
--   tipo hoje só 'resistencia_isolamento'; ôhmica, surge test etc. entram depois.
--   tensao_nominal_v / classe_isolamento / tipo_bobina são CÓPIA do motor no dia do ensaio:
--   se a placa for corrigida depois, o ensaio antigo continua avaliado pelo que valia.
--   medicoes em jsonb: [{ circuito, r30s, r1min, r10min, foraEscala }] em MΩ — lista curta,
--   sempre lida junto com o ensaio.
--   resultado: calculado no app (src/utils/eletrica-ensaio.ts) e gravado pra filtrar a lista.
--
-- Permissões (pedido do Lucas): qualquer usuário logado cadastra/edita motor e lança ensaio.
-- Ensaio só é corrigido por quem lançou (ou Admin). Excluir: só Admin.
--
-- Execute no Supabase SQL Editor: https://supabase.com/dashboard/project/_/sql

BEGIN;

-- ── Equipamentos (motores) ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.eletrica_equipamentos (
  id                  UUID          DEFAULT gen_random_uuid() PRIMARY KEY,
  tipo                TEXT          NOT NULL DEFAULT 'motor' CHECK (tipo IN ('motor')),
  tag                 TEXT          NOT NULL CHECK (btrim(tag) <> ''),
  descricao           TEXT,
  local_instalacao    TEXT,
  fabricante          TEXT,
  modelo              TEXT,
  numero_serie        TEXT,
  potencia_kw         NUMERIC(10,2),
  potencia_cv         NUMERIC(10,2),
  tensao_v            NUMERIC(10,1) NOT NULL CHECK (tensao_v > 0),
  corrente_a          NUMERIC(10,2),
  frequencia_hz       NUMERIC(5,1),
  fator_servico       NUMERIC(4,2),
  rotacao_rpm         INTEGER,
  classe_isolamento   TEXT          NOT NULL CHECK (classe_isolamento IN ('A', 'B', 'F', 'H')),
  -- IEEE 43-2013 tabela 3: define a resistência mínima.
  tipo_bobina         TEXT          NOT NULL CHECK (tipo_bobina IN ('pre_formada', 'randomica', 'antiga')),
  observacoes         TEXT,
  criado_por_id       UUID          REFERENCES public.profiles(id) ON DELETE SET NULL,
  criado_por_nome     TEXT,
  created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- TAG não repete (sem diferenciar maiúscula/minúscula nem espaço nas pontas).
CREATE UNIQUE INDEX IF NOT EXISTS uq_eletrica_equipamentos_tag ON public.eletrica_equipamentos (upper(btrim(tag)));

-- ── Ensaios ─────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.eletrica_ensaios (
  id                         UUID          DEFAULT gen_random_uuid() PRIMARY KEY,
  numero                     BIGINT        GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  equipamento_id             UUID          NOT NULL REFERENCES public.eletrica_equipamentos(id) ON DELETE CASCADE,
  tipo                       TEXT          NOT NULL DEFAULT 'resistencia_isolamento' CHECK (tipo IN ('resistencia_isolamento')),
  data_ensaio                DATE          NOT NULL,
  os_numero                  TEXT,
  -- Condições
  instrumento                TEXT,
  instrumento_modelo         TEXT,
  tensao_aplicada_v          NUMERIC(10,1) NOT NULL CHECK (tensao_aplicada_v > 0),
  temperatura_ambiente_c     NUMERIC(5,1)  NOT NULL,
  temperatura_enrolamento_c  NUMERIC(5,1),
  umidade_pct                NUMERIC(5,1)  CHECK (umidade_pct IS NULL OR umidade_pct BETWEEN 0 AND 100),
  -- Cópia da placa no dia do ensaio (critério da norma)
  tensao_nominal_v           NUMERIC(10,1) NOT NULL CHECK (tensao_nominal_v > 0),
  classe_isolamento          TEXT          NOT NULL CHECK (classe_isolamento IN ('A', 'B', 'F', 'H')),
  tipo_bobina                TEXT          NOT NULL CHECK (tipo_bobina IN ('pre_formada', 'randomica', 'antiga')),
  -- Leituras: [{ circuito, r30s, r1min, r10min, foraEscala }] (MΩ)
  medicoes                   JSONB         NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(medicoes) = 'array'),
  resultado                  TEXT          NOT NULL CHECK (resultado IN ('aprovado', 'reprovado')),
  -- Executantes: [{ nome, matricula }]
  executantes                JSONB         NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(executantes) = 'array'),
  observacoes                TEXT,
  criado_por_id              UUID          REFERENCES public.profiles(id) ON DELETE SET NULL,
  criado_por_nome            TEXT          NOT NULL,
  created_at                 TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at                 TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_eletrica_ensaios_equip ON public.eletrica_ensaios (equipamento_id, data_ensaio);

-- ── RLS ─────────────────────────────────────────────────────────────────────
ALTER TABLE public.eletrica_equipamentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eletrica_ensaios ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS portal_read ON public.eletrica_equipamentos;
DROP POLICY IF EXISTS eletrica_cadastrar ON public.eletrica_equipamentos;
DROP POLICY IF EXISTS eletrica_editar ON public.eletrica_equipamentos;
DROP POLICY IF EXISTS portal_admin_excluir ON public.eletrica_equipamentos;
DROP POLICY IF EXISTS portal_read ON public.eletrica_ensaios;
DROP POLICY IF EXISTS eletrica_lancar ON public.eletrica_ensaios;
DROP POLICY IF EXISTS eletrica_corrigir ON public.eletrica_ensaios;
DROP POLICY IF EXISTS portal_admin_excluir ON public.eletrica_ensaios;

CREATE POLICY portal_read ON public.eletrica_equipamentos FOR SELECT TO authenticated USING (true);
CREATE POLICY eletrica_cadastrar ON public.eletrica_equipamentos FOR INSERT TO authenticated
  WITH CHECK (criado_por_id = auth.uid());
CREATE POLICY eletrica_editar ON public.eletrica_equipamentos FOR UPDATE TO authenticated
  USING (true) WITH CHECK (true);
CREATE POLICY portal_admin_excluir ON public.eletrica_equipamentos FOR DELETE TO authenticated
  USING (public.portal_role() = 'Admin');

CREATE POLICY portal_read ON public.eletrica_ensaios FOR SELECT TO authenticated USING (true);
CREATE POLICY eletrica_lancar ON public.eletrica_ensaios FOR INSERT TO authenticated
  WITH CHECK (criado_por_id = auth.uid());
CREATE POLICY eletrica_corrigir ON public.eletrica_ensaios FOR UPDATE TO authenticated
  USING (criado_por_id = auth.uid() OR public.portal_role() = 'Admin')
  WITH CHECK (criado_por_id = auth.uid() OR public.portal_role() = 'Admin');
CREATE POLICY portal_admin_excluir ON public.eletrica_ensaios FOR DELETE TO authenticated
  USING (public.portal_role() = 'Admin');

-- Quem lançou não muda na correção (senão bastava trocar o dono pra editar ensaio alheio).
CREATE OR REPLACE FUNCTION public.portal_validar_ensaio() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF auth.role() = 'service_role' OR public.portal_role() = 'Admin' THEN RETURN NEW; END IF;
  IF NEW.criado_por_id IS DISTINCT FROM OLD.criado_por_id OR NEW.numero IS DISTINCT FROM OLD.numero THEN
    RAISE EXCEPTION 'Não é permitido trocar o número ou quem lançou o ensaio.' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS portal_validar_ensaio ON public.eletrica_ensaios;
CREATE TRIGGER portal_validar_ensaio BEFORE UPDATE ON public.eletrica_ensaios
FOR EACH ROW EXECUTE FUNCTION public.portal_validar_ensaio();

COMMIT;
