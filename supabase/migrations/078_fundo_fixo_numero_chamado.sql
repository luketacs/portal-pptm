-- Número do chamado do Fundo Fixo (exibido como FF-001, FF-002...), pra quem abriu a
-- solicitação conseguir se referir a ela ("meu chamado é o FF-012"). Contagem única
-- pra todo mundo, contínua (não reinicia por ano nem por pessoa).
--
-- O número é gerado pelo banco (identity), então os dois pontos que criam solicitação —
-- formulário interno (fundo-fixo.service.ts) e link público (api/fundo-fixo-public-request.js)
-- — recebem o número sozinhos, sem risco de repetir com dois envios ao mesmo tempo.
--
-- As solicitações que já existem são numeradas pela ordem em que foram abertas
-- (data_solicitacao); a sequência continua a partir da maior.
--
-- RODAR ANTES do deploy do front/API: eles já pedem a coluna `numero` no insert.
-- Execute no Supabase SQL Editor: https://supabase.com/dashboard/project/_/sql

BEGIN;

ALTER TABLE fundo_fixo_solicitacoes ADD COLUMN IF NOT EXISTS numero BIGINT;

-- portal_validar_fundo (migration 054) só libera alteração pra sessão de Admin /
-- service_role — no SQL Editor não há usuário logado e ela barraria o UPDATE do
-- preenchimento abaixo. Desligada só dentro desta transação (mesmo jeito da 066).
ALTER TABLE fundo_fixo_solicitacoes DISABLE TRIGGER portal_validar_fundo;

WITH ordem AS (
  SELECT id, row_number() OVER (ORDER BY data_solicitacao, created_at, id) AS n
    FROM fundo_fixo_solicitacoes
)
UPDATE fundo_fixo_solicitacoes f
   SET numero = ordem.n
  FROM ordem
 WHERE f.id = ordem.id
   AND f.numero IS NULL;

ALTER TABLE fundo_fixo_solicitacoes ENABLE TRIGGER portal_validar_fundo;

ALTER TABLE fundo_fixo_solicitacoes ALTER COLUMN numero SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_attribute
     WHERE attrelid = 'fundo_fixo_solicitacoes'::regclass AND attname = 'numero' AND attidentity <> ''
  ) THEN
    ALTER TABLE fundo_fixo_solicitacoes ALTER COLUMN numero ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;

-- Próximo número = maior existente + 1 (com a tabela vazia, começa em 1).
SELECT setval(
  pg_get_serial_sequence('fundo_fixo_solicitacoes', 'numero'),
  COALESCE((SELECT max(numero) FROM fundo_fixo_solicitacoes), 0) + 1,
  false
);

CREATE UNIQUE INDEX IF NOT EXISTS fundo_fixo_solicitacoes_numero_key
  ON fundo_fixo_solicitacoes (numero);

COMMIT;

-- Conferência: as mais recentes com o número.
SELECT numero, data_solicitacao, solicitante_nome, material
  FROM fundo_fixo_solicitacoes
 ORDER BY numero DESC
 LIMIT 10;
